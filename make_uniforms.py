def pixel(frame, x, y):
    """A frame's pixel as drawn in the stripes, blank off the sides of the frame."""
    if not 0 <= x < frame.get_width():
        return "."
    colour = frame.get_at((x, y))
    return PACK_COLOURS[tuple(colour)[:3]] if colour.a else "."


def stripes_on(frame, stripes, name):
    """The pixels of a frame to paint in the trim colour. Within a strip, the
    skater can sit a pixel or two to one side of the frame the stripes were
    drawn on."""
    for shift in (0, 1, -1, 2, -2):
        if all(pixel(frame, x + shift, y) == mark.replace("x", "o")
               for y, row in enumerate(stripes) for x, mark in enumerate(row)):
            return {(x + shift, y) for y, row in enumerate(stripes) for x, mark in enumerate(row) if mark == "x"}
    raise ValueError(f"the stripes for {name} don't match the drawing")


def paint(name, source, stripes, colours):
    strip = pygame.image.load(source)
    width = strip.get_width() // len(stripes)
    for i, frame_stripes in enumerate(stripes):
        frame = strip.subsurface((i * width, 0, width, strip.get_height()))
        trim = stripes_on(frame, frame_stripes, f"{name} frame {i}")
        for y in range(frame.get_height()):
            for x in range(width):
                if pixel(frame, x, y) == "o":
                    frame.set_at((x, y), colours["trim"] if (x, y) in trim else colours["main"])
    return strip


def main():
    UNIFORMS.mkdir(exist_ok=True)
    for team, colours in TEAMS.items():
        for name, (source, stripes) in STRIPS.items():
            strip = paint(name, source, stripes, colours)
            pygame.image.save(strip, UNIFORMS / f"Team_{team}_{name}_strip{len(stripes)}.png")
    print(f"Painted {len(TEAMS) * len(STRIPS)} strips into {UNIFORMS.name}/")


if __name__ == "__main__":
    main()
